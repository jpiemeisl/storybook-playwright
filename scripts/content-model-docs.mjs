#!/usr/bin/env node
/*
 * Generates docs/content-model.md from the JSDoc in src/content-types/{shared,blocks}.ts and the
 * per-block examples in src/fixtures/blocks/*.json.
 *
 *   node scripts/content-model-docs.mjs          write the file
 *   node scripts/content-model-docs.mjs --check  exit 1 if the file is out of date (used by a unit test)
 *
 * TypeScript 7 has no JavaScript compiler API, so this reads the source with a small line parser. It
 * relies on the doc format stated at the top of blocks.ts: a JSDoc comment above every interface and
 * field, and each field's type on one line.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'docs', 'content-model.md');

/** Parses `export interface X extends Y {` / `export type X = {` declarations and their fields. */
export function parseInterfaces(source) {
  const lines = source.split(/\r?\n/);
  const result = [];
  let doc = '';
  let collecting = null;
  let current = null;
  for (const raw of lines) {
    const line = raw.trim();
    if (collecting !== null) {
      collecting += ' ' + line.replace(/^\*\/?|\*\/$/g, '').trim();
      if (line.endsWith('*/')) {
        doc = collecting.replace(/\*\/$/, '').replace(/\s+/g, ' ').trim();
        collecting = null;
      }
      continue;
    }
    const single = line.match(/^\/\*\*\s*(.*?)\s*\*\/$/);
    if (single) {
      doc = single[1];
      continue;
    }
    if (line.startsWith('/**')) {
      collecting = line.replace(/^\/\*\*/, '').trim();
      continue;
    }
    const decl = line.match(/^export (?:interface (\w+)(?: extends ([\w, ]+))? \{|type (\w+) = \{)$/);
    if (decl) {
      current = { name: decl[1] ?? decl[3], extends: decl[2]?.split(',').map((s) => s.trim()) ?? [], doc, fields: [] };
      result.push(current);
      doc = '';
      continue;
    }
    if (current && /^\}/.test(line)) {
      current = null;
      doc = '';
      continue;
    }
    const field = current && line.match(/^(\w+)(\??): (.+);$/);
    if (field) {
      current.fields.push({ name: field[1], required: field[2] !== '?', type: field[3], doc });
      doc = '';
      continue;
    }
    if (line && !line.startsWith('//')) doc = '';
  }
  return result;
}

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function exampleValue(value) {
  if (value === undefined) return '';
  let json = JSON.stringify(value);
  if (json.length > 70) json = json.slice(0, 67) + '…';
  return '`' + json.replace(/`/g, "'") + '`';
}

function fieldTable(fields, example) {
  if (!example) {
    const rows = fields.map((f) => `| \`${f.name}\` | \`${cell(f.type)}\` | ${f.required ? 'yes' : 'no'} | ${cell(f.doc)} |`);
    return ['| Field | Type | Required | Description |', '| --- | --- | --- | --- |', ...rows].join('\n');
  }
  const rows = fields.map(
    (f) => `| \`${f.name}\` | \`${cell(f.type)}\` | ${f.required ? 'yes' : 'no'} | ${cell(f.doc)} | ${cell(exampleValue(example[f.name]))} |`,
  );
  return ['| Field | Type | Required | Description | Example |', '| --- | --- | --- | --- | --- |', ...rows].join('\n');
}

function allowedValues(fields) {
  const unions = fields.filter((f) => /^'[^']*'( \| '[^']*')+$/.test(f.type));
  if (!unions.length) return '';
  return '\n\nAllowed values: ' + unions.map((f) => `\`${f.name}\`: ${f.type.split(' | ').map((v) => '`' + v.slice(1, -1) + '`').join(', ')}`).join('; ') + '.';
}

export function generate() {
  const shared = parseInterfaces(readFileSync(join(root, 'src/content-types/shared.ts'), 'utf8'));
  const all = parseInterfaces(readFileSync(join(root, 'src/content-types/blocks.ts'), 'utf8'));
  const examplesDir = join(root, 'src/fixtures/blocks');
  const examples = Object.fromEntries(
    readdirSync(examplesDir)
      .filter((f) => f.endsWith('.json'))
      .map((f) => [f.replace(/\.json$/, ''), JSON.parse(readFileSync(join(examplesDir, f), 'utf8'))]),
  );

  const base = all.find((i) => i.name === 'BlockBase');
  const blocks = all.filter((i) => i.extends.includes('BlockBase'));
  const items = all.filter((i) => i !== base && !blocks.includes(i) && i.name !== 'PageContent');
  const page = all.find((i) => i.name === 'PageContent');
  const typeOf = (block) => block.fields.find((f) => f.name === 'type')?.type.replace(/'/g, '');

  const out = [];
  out.push(
    '# Content model',
    '',
    '<!-- GENERATED by scripts/content-model-docs.mjs from the JSDoc in src/content-types and the examples in src/fixtures/blocks. Do not edit by hand: run `npm run docs:content-model`. A unit test fails when this file is out of date. -->',
    '',
    'This file is **generated**. Field descriptions come from the JSDoc in [`src/content-types/blocks.ts`](../src/content-types/blocks.ts) and [`shared.ts`](../src/content-types/shared.ts); examples come from [`src/fixtures/blocks/`](../src/fixtures/blocks). Only the modelling guidance below is hand-written (inside the generator).',
    '',
    'The content model is plain JSON: no functions, React nodes or `Date` objects (dates are ISO 8601 strings). A CMS adapter maps CMS entries to `PageContent`; `<BlockRenderer>` maps each block to a component through the registry. Length limits mentioned below are guidance, not validation.',
    '',
    '## Modelling guidance',
    '',
    '- **One CMS content type per block type.** Keep CMS field names free; the adapter renames them. Do not model layout (columns, colours) as free text: use the enumerated values listed per block.',
    '- **Ids.** Every block needs an `id` unique within the page (CMS entry ids work well). `anchorId` is optional and separate: authors set it for `#links`; it must start with a letter and contain only letters, digits, `-` and `_`.',
    '- **Headings are automatic.** Authors never pick heading levels. The first `hero` or `pageHeader` on a page renders the `h1`; every other block heading is `h2`, and items inside blocks are `h3`. Start each page with a `hero` or `pageHeader`.',
    '- **Images need alt text.** `ImageRef.alt` is required. Use `""` only for decorative images (avatars beside a name, logos beside the company name). Image `src` must be relative or http(s).',
    '- **Links.** Allowed: relative URLs, `http(s):`, `mailto:` and `tel:`. Anything else (`javascript:`, `data:`, …) is reported by `validatePage`, and the renderer shows the link text without a link.',
    '- **Rich text** is `{ format: "html", html }`. The adapter must produce sanitized HTML from an allow-list (see `src/adapters/example-cms`); the renderer additionally strips unsafe URLs but is not a full sanitizer.',
    '- **Money** is integer minor units plus an ISO currency code (`{ "amount": 4900, "currency": "USD" }` is $49). `price: null` means "contact us".',
    '- **Forms** (`contactForm`, `newsletterSignup`) are content only. They become interactive when the host app passes handlers in `BlockRenderer`’s `context.forms`; otherwise they render as an inert preview.',
    '- **Tabs** may contain rich text or blocks, one level deep (no tabs inside tabs).',
    '- **Validate before publishing.** Run `validatePage(page)` in CMS preview or CI; errors make a block render as nothing (or a placeholder with `showErrors`).',
    '',
    '## Page',
    '',
    page.doc,
    '',
    fieldTable(page.fields),
    '',
    '## Fields on every block',
    '',
    base.doc,
    '',
    fieldTable(base.fields) + allowedValues(base.fields),
    '',
    '## Blocks',
    '',
    blocks.map((b) => `- [\`${typeOf(b)}\`](#${typeOf(b).toLowerCase()}): ${b.doc}`).join('\n'),
    '',
  );
  for (const block of blocks) {
    const type = typeOf(block);
    const fields = block.fields.filter((f) => f.name !== 'type');
    out.push(`### ${type}`, '', `${block.doc} TypeScript: \`${block.name}\`. Example: [\`src/fixtures/blocks/${type}.json\`](../src/fixtures/blocks/${type}.json).`, '', fieldTable(fields, examples[type]) + allowedValues(fields), '');
  }
  out.push('## Item shapes', '');
  for (const item of items) {
    out.push(`### ${item.name}`, '', item.doc + (item.extends.length ? ` Extends ${item.extends.map((e) => '`' + e + '`').join(', ')}.` : ''), '', fieldTable(item.fields) + allowedValues(item.fields), '');
  }
  out.push('## Shared types', '', 'From `src/content-types/shared.ts`. Navigation types (`NavItem`, `BreadcrumbItem`, `SocialLink`) and `Money` live in `navigation.ts` and `money.ts`.', '');
  for (const item of shared) {
    out.push(`### ${item.name}`, '', item.doc + (item.extends.length ? ` Extends ${item.extends.map((e) => '`' + e + '`').join(', ')}.` : ''), '', fieldTable(item.fields) + allowedValues(item.fields), '');
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const content = generate();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    } catch {}
    if (current !== content) {
      console.error('docs/content-model.md is out of date. Run: npm run docs:content-model');
      process.exit(1);
    }
    console.log('docs/content-model.md is up to date.');
  } else {
    writeFileSync(OUT, content);
    console.log('Wrote docs/content-model.md');
  }
}
