#!/usr/bin/env node
/*
 * Generates docs/COMPONENTS.md from storybook-static/index.json (run npm run build-storybook first):
 * one row per Storybook title under src/ (components, templates, commerce), with its source folder, tags
 * and number of stories (states). `--check` exits 1 when the committed file is out of date.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const indexPath = resolve(process.cwd(), 'storybook-static', 'index.json');
const outPath = resolve(process.cwd(), 'docs', 'COMPONENTS.md');
if (!existsSync(indexPath)) {
  console.error('storybook-static/index.json not found. Run npm run build-storybook first.');
  process.exit(1);
}

const DEFAULT_TAGS = new Set(['dev', 'test', 'autodocs', 'play-fn']);
const entries = Object.values(JSON.parse(readFileSync(indexPath, 'utf8')).entries).filter((e) => e.type === 'story' && e.importPath.startsWith('./src/'));

const byTitle = new Map();
for (const e of entries) {
  const row = byTitle.get(e.title) ?? { title: e.title, folder: e.importPath.replace(/^\.\//, '').replace(/\/[^/]+$/, ''), stories: 0, tags: new Set() };
  row.stories += 1;
  for (const tag of e.tags ?? []) if (!DEFAULT_TAGS.has(tag)) row.tags.add(tag);
  byTitle.set(e.title, row);
}

const area = (folder) => (folder.startsWith('src/commerce/templates') ? 'Commerce templates' : folder.startsWith('src/commerce') ? 'Commerce components' : folder.startsWith('src/templates') ? 'Templates' : folder.startsWith('src/components') ? 'Core components' : 'Foundations and other');
const groups = new Map();
for (const row of [...byTitle.values()].sort((a, b) => a.title.localeCompare(b.title))) {
  const key = area(row.folder);
  groups.set(key, [...(groups.get(key) ?? []), row]);
}

const order = ['Core components', 'Templates', 'Commerce components', 'Commerce templates', 'Foundations and other'];
const lines = [
  '# Components',
  '',
  '<!-- Generated by `npm run docs:components` from the Storybook index. Do not edit by hand; `npm run check:all` fails when this file is stale. -->',
  '',
  `${byTitle.size} Storybook titles and ${entries.length} stories under \`src/\`. "Stories" counts the documented states. Tags: \`vrt-full\` and \`vrt-mobile\` choose screenshot widths, \`theme-smoke\` adds the extra themes, \`skip-vrt\` means not captured.`,
  '',
];
for (const key of order.filter((k) => groups.has(k))) {
  lines.push(`## ${key}`, '', '| Component | Storybook title | Folder | Tags | Stories |', '| --- | --- | --- | --- | --- |');
  for (const row of groups.get(key)) {
    const name = row.title.split('/').pop();
    const tags = [...row.tags].sort().map((t) => `\`${t}\``).join(' ') || '–';
    lines.push(`| ${name} | ${row.title} | \`${row.folder}\` | ${tags} | ${row.stories} |`);
  }
  lines.push('');
}
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== output) {
    console.error('docs/COMPONENTS.md is out of date. Run npm run docs:components and commit the result.');
    process.exit(1);
  }
  console.log(`docs/COMPONENTS.md is up to date (${byTitle.size} titles).`);
} else {
  writeFileSync(outPath, output);
  console.log(`Wrote docs/COMPONENTS.md (${byTitle.size} titles, ${entries.length} stories).`);
}
