#!/usr/bin/env node
/*
 * Proves the package works in a fresh consuming app, outside this repository:
 *   node scripts/smoke-app.mjs <package> <empty-directory> [--registry]
 * <package> is a tarball from `npm pack` (CI's package job) or `@jpiemeisl/pattern-library@<version>`
 * with --registry (the release workflow's post-publish check, installing from GitHub Packages).
 * Creates a minimal Vite + React + TypeScript app in the directory, installs the package with the
 * repository's own versions of react, react-dom, vite, typescript and the type packages, imports from
 * the core and commerce entry points and the CSS entry points, then typechecks and builds the app.
 * With --registry it writes an .npmrc for the @jpiemeisl scope that reads the token from NODE_AUTH_TOKEN
 * at install time; the token itself is never written to disk.
 */
import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const [spec, dirArg] = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const fromRegistry = process.argv.includes('--registry');
if (!spec || !dirArg) {
  console.error('Usage: node scripts/smoke-app.mjs <tarball | name@version> <empty-directory> [--registry]');
  process.exit(1);
}
const root = process.cwd();
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const dir = resolve(dirArg);
if (existsSync(dir) && readdirSync(dir).length) {
  console.error(`${dir} is not empty.`);
  process.exit(1);
}
mkdirSync(join(dir, 'src'), { recursive: true });

/** The version this repository actually installed, so the smoke app matches what CI tested. */
const installed = (name) => JSON.parse(readFileSync(resolve(root, 'node_modules', name, 'package.json'), 'utf8')).version;
const tools = ['react', 'react-dom', 'vite', '@vitejs/plugin-react', 'typescript', '@types/react', '@types/react-dom'].map((name) => `${name}@${installed(name)}`);
const target = fromRegistry ? spec : resolve(spec);
const name = pkg.name;

const write = (file, text) => writeFileSync(join(dir, file), text);
write('package.json', JSON.stringify({ name: 'pattern-library-smoke-app', private: true, type: 'module' }, null, 2) + '\n');
if (fromRegistry) {
  const scope = name.split('/')[0];
  // ${NODE_AUTH_TOKEN} is expanded by npm when it reads the file; the token never touches the disk.
  write('.npmrc', `${scope}:registry=https://npm.pkg.github.com\n//npm.pkg.github.com/:_authToken=\${NODE_AUTH_TOKEN}\n`);
}
write('index.html', '<!doctype html>\n<html lang="en">\n  <head><meta charset="UTF-8" /><title>Smoke test</title></head>\n  <body><div id="root"></div><script type="module" src="/src/main.tsx"></script></body>\n</html>\n');
write('vite.config.mjs', "import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\n\nexport default defineConfig({ plugins: [react()], build: { chunkSizeWarningLimit: 4096 } });\n");
write(
  'tsconfig.json',
  JSON.stringify(
    {
      compilerOptions: { target: 'ES2022', module: 'ESNext', moduleResolution: 'bundler', jsx: 'react-jsx', strict: true, noEmit: true, skipLibCheck: false, types: [], lib: ['ES2022', 'DOM', 'DOM.Iterable'] },
      include: ['src'],
    },
    null,
    2,
  ) + '\n',
);
write('src/css.d.ts', "declare module '*.css';\n");
write(
  'src/main.tsx',
  `// Generated by scripts/smoke-app.mjs: uses each entry point the way docs/consuming.md describes.
import '${name}/tokens.css';
import '${name}/themes/harbor.css';
import '${name}/core.css';
import '${name}/commerce.css';
import { StrictMode, type ReactNode } from 'react';
import { createRoot } from 'react-dom/client';
import { Button, Heading, LinkProvider, Link, Theme, createTemplates, themes, type LinkComponentProps, type ThemeName } from '${name}';
import { commerceTemplates, type CommerceContext } from '${name}/commerce';

const templates = createTemplates(Object.values(commerceTemplates));
const RouterLink = (props: LinkComponentProps): ReactNode => <a {...props} data-router="true" />;
const theme: ThemeName = themes[1].name;
const ctx: Partial<CommerceContext> = {};

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <LinkProvider component={RouterLink}>
      <Theme name={theme}>
        <Heading as="h1" size="2xl">Smoke test</Heading>
        <p>{Object.keys(templates).length} templates, context keys: {Object.keys(ctx).length}</p>
        <Link href="/cart">Cart</Link>
        <Button variant="primary">Buy</Button>
      </Theme>
    </LinkProvider>
  </StrictMode>,
);
`,
);

const run = (command) => {
  console.log(`\n$ ${command}`);
  execSync(command, { cwd: dir, stdio: 'inherit' });
};
// Fixed commands; the only interpolated values are the package spec and version pins from package files.
run(`npm install --no-audit --no-fund --loglevel=error ${JSON.stringify(target)} ${tools.join(' ')}`);
run('npx tsc -p tsconfig.json');
run('npx vite build --logLevel warn');

const assets = readdirSync(join(dir, 'dist', 'assets'));
const css = assets.filter((f) => f.endsWith('.css')).map((f) => readFileSync(join(dir, 'dist', 'assets', f), 'utf8')).join('\n');
const js = assets.filter((f) => f.endsWith('.js')).map((f) => readFileSync(join(dir, 'dist', 'assets', f), 'utf8')).join('\n');
const problems = [];
if (!css.includes('--color-bg')) problems.push('the built CSS has no semantic tokens (tokens.css)');
if (!css.includes("data-theme='harbor'") && !css.includes('data-theme="harbor"') && !css.includes('data-theme=harbor')) problems.push('the built CSS has no harbor theme');
if (!js.includes('data-router')) problems.push('the built JavaScript is missing the app code');
if (problems.length) {
  console.error(`\nSmoke test failed: ${problems.join('; ')}.`);
  process.exit(1);
}
const installedVersion = JSON.parse(readFileSync(join(dir, 'node_modules', ...name.split('/'), 'package.json'), 'utf8')).version;
console.log(`\nSmoke test OK: ${name}@${installedVersion} installed from ${fromRegistry ? 'the registry' : 'the tarball'}, typechecked and built (${assets.length} assets).`);
